-- 출하 전 검수 필수 정책 기본값 Y → N (docs/79 Q4, 2026-11-16 사용자 결정) — 임시 번호(docs/29 2.2, 병합 때 이름만 바뀐다)
--
-- - 출하 전 검수(docs/78)는 장비 제조 성격 기능이라 일반 공장에서는 기본으로 출하 확정을 막지 않는다.
--   검수를 쓰는 회사는 정책 화면(sys-policy)에서 QMS_PRESHIP_REQUIRED = Y 로 켠다. 화면·양식은 메뉴에 그대로 보인다.
-- - 회사가 이미 값을 저장했으면(sys_policy 행) 그 값이 이긴다 — 이 파일은 전역 기본값만 바꾼다.
-- - 남의 표 변경 없음(전역 sys_policy_def 한 행)
-- =====================================================================

UPDATE sys_policy_def SET default_value = 'N' WHERE policy_key = 'QMS_PRESHIP_REQUIRED';
